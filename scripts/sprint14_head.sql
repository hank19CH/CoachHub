update public.exercise_library set load_type = case
    when category in ('warmup','cooldown') then 'none'
    when category = 'plyometric' and name ilike any (array['%slam%','%throw%','%push-up%']) then 'external_load'
    when category = 'plyometric' then 'contacts'
    when name ilike any (array['%sprint%','%falling start%','%block start%','%tempo%','%run%','%strides%']) then 'distance'
    when name ilike any (array['%battle rope%','%plank%','%hang%','%carry%']) then 'time'
    when name ilike any (array['%medicine ball%','%med ball%','%kettlebell%']) then 'external_load'
    when category = 'drill' and movement_pattern = 'locomotion' then 'none'
    when name ilike any (array['%chin-up%','%pull-up%','%push-up%','%dip%','%bird dog%','%ab wheel%',
                               '%inverted row%','%back extension%','%nordic%','%copenhagen%']) then 'bodyweight'
    when category in ('primary','accessory') or movement_pattern = 'skill' then 'external_load'
    else 'none' end
where load_type is null;

-- ─── 8. Make the 13 system season templates shape-aware ─────────────
-- Adds {"shape","deload"} to every block so a season template can be modeled
-- block-by-block. Vocabulary verified against production structure->blocks.
update public.periodization_templates p
set structure = jsonb_set(p.structure, '{blocks}', (
  select jsonb_agg(b || jsonb_build_object(
    'shape', case
      when b->>'type' = 'competition' and b->>'intensity' in ('peak','high') then 'peak'
      when b->>'type' in ('competition','deload') then 'maintain'
      when b->>'volume' = 'low' and b->>'intensity' = 'moderate' then 'maintain'
      when b->>'volume' = 'high' and b->>'intensity' = 'high' then 'steady_build'
      when b->>'intensity' = 'high' then 'intensify'
      when b->>'volume' = 'high' or b->>'intensity' = 'low' then 'accumulate'
      else 'steady_build' end,
    'deload', case when b->>'type' in ('competition','deload')
                     or (b->>'volume' = 'low' and b->>'intensity' = 'moderate') then 'none' else 'every_4' end,
    'is_deload_block', b->>'type' = 'deload'
  ) order by ord)
  from jsonb_array_elements(p.structure->'blocks') with ordinality as x(b, ord)
))
where p.coach_id is null
  and jsonb_typeof(p.structure->'blocks') = 'array'
  and not (p.structure->'blocks'->0 ? 'shape');

