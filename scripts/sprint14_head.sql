-- Tells the engine/UI what "volume" means for an exercise. Backfill is conservative;
-- coaches can correct in the library later.
alter table public.exercise_library add column if not exists load_type text;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'exercise_library_load_type_check') then
    alter table public.exercise_library add constraint exercise_library_load_type_check
      check (load_type is null or load_type in ('external_load','bodyweight','distance','time','contacts','none'));
